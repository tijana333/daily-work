/* ========================================
HTML ESCAPING
Converts special characters so user input
is shown as text instead of being run as HTML
===========================================*/
export function escapeHtml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
